"""README.md from README.tmpl.md, and llms.txt, from the classified snapshot.

Template directives, each alone on a line:
  {{links}}      website, X and email from the GitHub profile
  {{sections}}   one heading + list per category in profile.json, ranked
  {{lately N}}   the N most recently pushed visible repos with their last commit
"""

from __future__ import annotations

import re

from projects import Placement, Repo, rank


def _stars(r: Repo) -> str:
    return f" `★ {r.stars:,}`" if r.stars else ""


def links(profile: dict) -> str:
    parts = []
    if blog := (profile.get("blog") or "").strip():
        url = blog if "://" in blog else f"https://{blog}"
        parts.append(f"[{re.sub(r'^https?://', '', blog).rstrip('/')}]({url})")
    if x := profile.get("twitter_username"):
        parts.append(f"[x/@{x}](https://x.com/{x})")
    if mail := profile.get("email"):
        parts.append(f"[mail](mailto:{mail})")
    return " · ".join(parts)


def sections(placements: list[Placement], cfg: dict) -> str:
    out = []
    for cat in cfg["categories"]:
        members = rank([p for p in placements if p.category == cat["id"]])[: cat.get("limit", 6)]
        if not members:
            continue
        out.append(f"### {cat['title']}\n")
        out += [f"- [**{p.repo.name}**]({p.repo.url}){_stars(p.repo)}: {p.repo.description}"
                for p in members]
        out.append("")
    return "\n".join(out).rstrip()


def lately(placements: list[Placement], n: int) -> str:
    visible = [p.repo for p in placements if p.category and p.repo.committed]
    visible.sort(key=lambda r: r.committed, reverse=True)
    return "\n".join(
        f"- `{r.committed:%b %d}`".lower() + f" [{r.name}]({r.url}): {r.commit}" for r in visible[:n])


def render(tmpl: str, profile: dict, placements: list[Placement], cfg: dict) -> str:
    def directive(m: re.Match) -> str:
        cmd, _, arg = m.group(1).strip().partition(" ")
        if cmd == "links":
            return links(profile)
        if cmd == "sections":
            return sections(placements, cfg)
        if cmd == "lately":
            return lately(placements, int(arg or 4))
        raise ValueError(f"unknown template directive {{{{{m.group(1)}}}}}")

    header = "<!-- generated by scripts/build.py from README.tmpl.md and profile.json; edit those -->\n"
    return header + re.sub(r"\{\{(.+?)\}\}", directive, tmpl)


def llms(profile: dict, placements: list[Placement], cfg: dict) -> str:
    """llms.txt (llmstxt.org): what each tool is and the file an agent should read to set it up."""
    lines = [f"# {profile.get('name') or cfg['user']}", "", f"> {cfg['llms']['summary']}", ""]
    titles = {c["id"]: c["title"] for c in cfg["categories"]}
    for cat in cfg["llms"]["categories"]:
        members = rank([p for p in placements if p.category == cat])
        if not members:
            continue
        lines += [f"## {titles[cat]}", ""]
        for p in members:
            r = p.repo
            guide = next((f for f in ("AGENT-SETUP.md", "README.md") if f in r.files), None)
            raw = (f"https://raw.githubusercontent.com/{cfg['user']}/{r.name}/{r.branch}/{guide}"
                   if guide else r.url)
            lines.append(f"- [{r.name}]({raw}): {r.description}. Source: {r.url}")
        lines.append("")
    return "\n".join(lines)
